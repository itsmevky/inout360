const runWorkingHoursCheck = async () => {
    console.log("🕒 Running Working Hours Violation Check...");
    try {
        // 1. Fetch enabled settings
        const settingsList = await SettingsModel.find({ "workingHours.enabled": true }).lean();

        for (const settings of settingsList) {
            if (!settings.unitLocation) continue;

            const { endTime } = settings.workingHours || {};
            if (!endTime) continue;

            // 2. Find logged-in Users & Visitors at this location
            const [employees, visitors] = await Promise.all([
                EmployeeModel.find({ location: settings.unitLocation }).select("employeeId").lean(),
                VisitorModel.find({ location: settings.unitLocation }).select("employeeId").lean(),
            ]);

            const employeeIds = new Set([
                ...employees.map(e => e.employeeId).filter(Boolean),
                ...visitors.map(v => v.employeeId).filter(Boolean)
            ]);

            if (employeeIds.size === 0) continue;

            // Find sessions that are "Logged In" for these employees
            // We check User & Visitor models for sessionStatus

            // Check Employees (via User model mostly)
            const loggedInUsers = await UserModel.find({
                employeeId: { $in: Array.from(employeeIds) },
                sessionStatus: "Logged In"
            }).select("_id name employeeId").lean();

            // Check Visitors
            const loggedInVisitors = await VisitorModel.find({
                employeeId: { $in: Array.from(employeeIds) },
                sessionStatus: "Logged In"
            }).select("_id name employeeId").lean();

            const violators = [
                ...loggedInUsers.map(u => ({ ...u, type: "Employee" })),
                ...loggedInVisitors.map(v => ({ ...v, type: "Visitor" }))
            ];

            if (violators.length === 0) continue;

            console.log(`⚠️ Found ${violators.length} violations at ${settings.unitLocation}`);

            // 3. Log Events
            const events = [];
            const timestamp = new Date(); // Logs at 00:05, but conceptually refers to prev day

            for (const violator of violators) {
                // Try to find the device they are using
                const device = await DeviceModel.findOne({
                    $or: [
                        { userId: violator._id },
                        { employeeId: violator.employeeId }
                    ]
                }).select("_id deviceId").lean();

                // If specific requirement is "shown with deviceId", we log empty if no device found
                // but we still log the violation for the user.

                events.push({
                    deviceId: device?._id || new require("mongoose").Types.ObjectId(), // Placeholder if no device
                    event: "Working Hours Violation",
                    name: violator.name || "Unknown",
                    employeeId: violator.employeeId,
                    timestamp,
                    policyVoilation: true,
                    metadata: {
                        reason: "working_hours_violation",
                        expectedLogout: endTime,
                        userType: violator.type,
                        foundStatus: "Logged In",
                        deviceId: device?.deviceId || "No Device Linked"
                    },
                    raw: { autoGenerated: true, location: settings.unitLocation }
                });
            }

            if (events.length > 0) {
                await DeviceEventModel.insertMany(events);
            }
        }
    } catch (error) {
        console.error("❌ Working Hours Check Error:", error.message);
    }
};

